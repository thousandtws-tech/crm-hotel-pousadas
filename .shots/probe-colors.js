const { chromium } = require('playwright-core');
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
(async () => {
  const browser = await chromium.launch({ executablePath: CHROME });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.goto('http://localhost:4200/login', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(800);
  await page.fill('input[formcontrolname="login"]', 'admin');
  await page.fill('input[formcontrolname="senha"]', 'admin123');
  await page.click('button[type="submit"]');
  await page.waitForURL('**/dashboard', { timeout: 15000 });
  await page.waitForTimeout(1000);
  await page.goto('http://localhost:4200/clientes', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(1500);
  const info = await page.evaluate(() => {
    const out = {};
    const rows = document.querySelectorAll('tr.mat-mdc-row, table.plain tbody tr');
    out.rows = [...rows].slice(0, 4).map(r => getComputedStyle(r).backgroundColor);
    const cells = document.querySelectorAll('.mat-mdc-cell, table.plain td');
    out.cells = [...cells].slice(0, 4).map(c => getComputedStyle(c).backgroundColor);
    const pag = document.querySelector('mat-paginator, .mat-mdc-paginator');
    out.paginator = pag ? getComputedStyle(pag).backgroundColor : 'none';
    const tbl = document.querySelector('table');
    out.table = tbl ? getComputedStyle(tbl).backgroundColor : 'none';
    const hdr = document.querySelector('.mat-mdc-header-row, table.plain thead tr');
    out.headerRow = hdr ? getComputedStyle(hdr).backgroundColor : 'none';
    const page_ = document.querySelector('.page');
    out.page = page_ ? getComputedStyle(page_).backgroundColor : 'none';
    return out;
  });
  console.log(JSON.stringify(info, null, 2));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
