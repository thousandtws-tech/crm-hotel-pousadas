const { chromium } = require('playwright-core');
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
(async () => {
  const browser = await chromium.launch({ executablePath: CHROME });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const out = 'D:/clientes/projeto-clarituz-crm-hotel-pousadas/.shots/';
  await page.goto('https://admin-production-2c55.up.railway.app/login', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2000);
  await page.screenshot({ path: out + 'prod-login.png' });
  await page.fill('input[formcontrolname="login"]', 'admin');
  await page.fill('input[formcontrolname="senha"]', 'Espirito2025!');
  await page.click('button[type="submit"]');
  await page.waitForURL('**/dashboard', { timeout: 20000 });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: out + 'prod-dashboard.png' });
  await page.goto('https://web-production-5b3105.up.railway.app', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: out + 'prod-web.png' });
  await browser.close();
  console.log('ok');
})().catch(e => { console.error(e); process.exit(1); });
